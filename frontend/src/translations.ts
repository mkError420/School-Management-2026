import { Language } from './types';

// Convert English numerals (0-9) to Bangla numerals (০-৯)
export function toBanglaDigits(num: number | string | null | undefined): string {
  if (num === null || num === undefined) return '';
  const banglaDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (digit) => banglaDigits[parseInt(digit, 10)]);
}

// Format numbers nicely in BDT Currency (৳)
export function formatCurrencyBDT(amount?: number | string | null, lang: Language = 'en'): string {
  if (amount === null || amount === undefined || amount === '') {
    const zero = (0).toLocaleString('en-IN');
    return lang === 'bn' ? `৳ ${toBanglaDigits(zero)}` : `৳ ${zero}`;
  }
  const numericVal = typeof amount === 'number' ? (isNaN(amount) ? 0 : amount) : (Number(amount) || 0);
  const formatted = numericVal.toLocaleString('en-IN');
  if (lang === 'bn') {
    return `৳ ${toBanglaDigits(formatted)}`;
  }
  return `৳ ${formatted}`;
}

